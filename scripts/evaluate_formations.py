"""Evaluate formation detection against the official DFL lineups.

    uv run python scripts/evaluate_formations.py            # match J03WMX

Splits the match into 5-minute windows (ball in play only, sampled at 5 fps),
detects each team's formation per window, and compares it with the official
starting formation. Runs three variants: all frames, frames where the team
has the ball, and frames where the opponent has it. Writes
evals/formation_eval.md.
"""

import sys
from collections import Counter
from pathlib import Path

import pandas as pd

from tactics.data.load import get_frames, load_dfl_match
from tactics.geometry.formation import average_positions, base_formation, detect_formation

ROOT = Path(__file__).resolve().parents[1]
WINDOW_S = 300
SAMPLE_EVERY = 5  # frames; 25 fps -> 5 fps is plenty for average positions
VARIANTS = ["all", "in possession", "out of possession"]


def select(players: pd.DataFrame, ball: pd.DataFrame, team: str, variant: str) -> pd.DataFrame:
    """Players rows for frames where the ball is in play, filtered by possession."""
    frames = ball[ball["alive"]]
    if variant == "in possession":
        frames = frames[frames["owning_team"] == team]
    elif variant == "out of possession":
        frames = frames[frames["owning_team"].notna() & (frames["owning_team"] != team)]
    return players[players["frame"].isin(frames["frame"])]


def markdown_table(df: pd.DataFrame) -> str:
    """Render a small DataFrame as a Markdown table."""
    header = "| " + " | ".join(df.columns) + " |"
    divider = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, divider, *body])


def main(match_id: str) -> None:
    match = load_dfl_match(ROOT / "data" / "raw" / "dfl", match_id)
    tracking = match.tracking
    players, ball = get_frames(match, int(tracking["frame_id"].min()), int(tracking["frame_id"].max()))
    keep = ball["frame"] % SAMPLE_EVERY == 0
    ball = ball[keep]
    players = players[players["frame"].isin(ball["frame"])]
    ball = ball.assign(window=(ball["time_s"] // WINDOW_S).astype(int))

    lines = [f"# Formation detection vs official lineup — match {match_id}", "",
             f"{match.home.name} v {match.away.name}. Windows of {WINDOW_S // 60} min, ball in play only, "
             f"sampled every {SAMPLE_EVERY} frames. Generated by `scripts/evaluate_formations.py`.", ""]
    summary = []
    for team in (match.home, match.away):
        attacking_right = team.side == "home"  # load_dfl_match orients home left -> right
        rows, results = [], {variant: [] for variant in VARIANTS}
        for (period, window), window_ball in ball.groupby(["period", "window"]):
            window_players = players[players["frame"].isin(window_ball["frame"])]
            row = {"window": f"P{period} {window * 5:02d}-{window * 5 + 5:02d} min"}
            for variant in VARIANTS:
                subset = select(window_players, window_ball, team.side, variant)
                if subset["frame"].nunique() < 50:  # under 10 s of play: too little to judge
                    row[variant] = "–"
                    continue
                if len(average_positions(subset, team.side, attacking_right)) < 10:
                    row[variant] = "(<10 outfield)"  # e.g. after a red card: templates assume 10
                    continue
                result = detect_formation(subset, team.side, attacking_right)[0]
                results[variant].append(result)
                row[variant] = result.formation
            rows.append(row)
        table = pd.DataFrame(rows)

        official = base_formation(team.formation)
        lines += [f"## {team.name} — official: {team.formation} (compared as {official})", ""]
        official_back_line = official.split("-")[0]
        for variant in VARIANTS:
            found = results[variant]
            exact = sum(r.formation == official for r in found) / len(found)
            top2 = sum(official in [name for name, _ in r.ranking[:2]] for r in found) / len(found)
            back = sum(r.formation.split("-")[0] == official_back_line for r in found) / len(found)
            if not found:
                lines.append(f"- **{variant}**: no window with 10 regular outfield players")
                continue
            whole = detect_formation(select(players, ball, team.side, variant), team.side, attacking_right)[0]
            top = ", ".join(f"{name} ({cost:.4f})" for name, cost in whole.ranking[:3])
            summary.append((team.name, variant, exact, top2, back, len(found)))
            lines.append(f"- **{variant}** ({len(found)} windows): exact {exact:.0%}, official in top 2 {top2:.0%}, "
                         f"back line ({official_back_line}) correct {back:.0%}. "
                         f"Most common: {Counter(r.formation for r in found).most_common(3)}. "
                         f"Whole match: {whole.formation} (top 3 by cost: {top})")
        lines += ["", markdown_table(table), ""]

    out = ROOT / "evals" / f"formation_eval_{match_id}.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"{'team':22} {'variant':18} {'exact':>6} {'top-2':>6} {'back line':>10}  windows")
    for name, variant, exact, top2, back, n in summary:
        print(f"{name:22} {variant:18} {exact:6.0%} {top2:6.0%} {back:10.0%}  {n}")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "J03WMX")
